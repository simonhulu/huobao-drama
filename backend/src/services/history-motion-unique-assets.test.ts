function fixture(t:TestContext) {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'motion-unique-')),materials=path.join(root,'materials');fs.mkdirSync(materials)
  let rows:any[]=[]
  const service=createHistoryMotionProduction({databasePath:path.join(root,'jobs.db'),root:path.join(root,'outputs'),materialRoot:materials,library:{search:()=>rows}})
  t.after(()=>{service.close();fs.rmSync(root,{recursive:true,force:true})})
  const candidate=(id:string,bytes=id)=>{const localPath=path.join(materials,`${id}.mp4`);fs.writeFileSync(localPath,bytes);return {assetId:id,rank:1,status:'done',sourceCaption:'行军队伍',query:'红军',text:'',duration:8,width:1920,height:1080,localPath,sha256:hashText(bytes),projectId:'p',clipId:'c'}}
  const lines=['红军出发。','队伍行进。'],script=lines.join('')
  const job=service.createPlan(1,motionPlanSchema.parse({scriptRevision:hashText(script),profile:'16:9',shots:lines.map((narration,i)=>({shotId:`s${i+1}`,narration,duration:2,visualType:'auto',search:{query:'红军'},imagePrompt:'同一人物场景',titles:[]}))}),script,'红军')
  let renderCalls=0,failRender=false;const prompts:string[]=[]
  const overrides={
    audio:async(_s:string,directory:string,_request?:{voiceId?:string})=>{const audioPath=path.join(directory,'voice.m4a');fs.writeFileSync(audioPath,'voice');return {audioPath,duration:4}},
    probeVideo:async()=>({duration:8,width:1920,height:1080}),
    reviewVideo:async()=>({status:'unavailable' as const,decision:'uncertain' as const,reason:'fixture',method:'two-frame-model-review' as const,limitations:'fixture'}),
    generateImage:async(input:any)=>{prompts.push(input.prompt);const filename=path.join(input.directory,`${input.shotId}.png`);fs.writeFileSync(filename,`image-${input.shotId}`);return {path:filename,sha256:hashText(`image-${input.shotId}`)}},
    render:async(_p:any,directory:string)=>{renderCalls++;if(failRender)throw Error('render failure');const outputPath=path.join(directory,'movie.mp4');fs.writeFileSync(outputPath,'movie');return {outputPath,report:{sha256:hashText('movie'),qa:{technical:'passed'}}}},
    deliver:async()=>({status:'attached'}),
  }
  return {root,service,job,candidate,setRows:(value:any[])=>{rows=value},overrides,prompts,renderCalls:()=>renderCalls,setFailRender:(value:boolean)=>{failRender=value}}
}
