test('explicit image rejection gets one saved nonviolent scene, retry keeps completed shots and narration',async t=>{
  const f=fixture(t),script=f.job.script,prompts:string[]=[],modelInputs:any[]=[]
  let audioCalls=0,failAlternative=true
  f.job.requested.shots[1].graphic={kind:'quote',title:'行进',items:[{label:'队伍行进'}]};f.service.write(f.job)
  const runner=createMotionRunner(f.service,{...f.overrides,
    audio:async(...args)=>{audioCalls++;return f.overrides.audio(...args)},
    model:async(system,input)=>{assert.match(system,/非暴力/);modelInputs.push(input);return {imagePrompt:'历史情景插画，远山旁的安静营地，人物整理行囊。'}},
    generateImage:async input=>{
      prompts.push(input.prompt)
      if(input.shotId==='s2' && !input.prompt.includes('安静营地'))throw Object.assign(Error('图片服务拒绝了原画面'),{code:'content_policy_violation'})
      if(input.shotId==='s2' && failAlternative)throw Error('图片服务超时，原请求已保留')
      return f.overrides.generateImage(input)
    },
  })
  runner.schedule(f.job.id);await runner.idle()
  const paused=f.service.find(f.job.id)!
  assert.equal(paused.status,'queued');assert.match(paused.retry!.lastError,/自动补图未完成.*图片服务超时/)
  assert.doesNotMatch(paused.retry!.lastError,/请重试或补充素材/)
  assert.ok(paused.plan!.visuals.s1);assert.equal(paused.plan!.imageRecoveries.s2.status,'failed')
  assert.equal(modelInputs.length,1);assert.equal(f.renderCalls(),0)
  failAlternative=false;runner.schedule(f.job.id);await runner.idle()
  const completed=f.service.find(f.job.id)!
  assert.equal(completed.status,'completed',completed.error || '')
  assert.equal(audioCalls,1);assert.equal(modelInputs.length,1)
  assert.equal(prompts.length,4);assert.equal(prompts[2],prompts[3])
  assert.ok(!prompts[2].includes('叙事意图：'))
  assert.equal(completed.script,script);assert.equal(completed.plan!.shots.map((s:any)=>s.narration).join(''),script)
  assert.equal(completed.plan!.shots[1].visualType,'image');assert.ok(completed.plan!.shots[1].graphic)
  assert.equal(completed.plan!.imageRecoveries.s2.status,'completed')
  assert.equal(completed.plan!.fallbacks.filter((item:any)=>item.stage==='image-rejection').length,1)
})

